class Product {
  final String id;
  String name;
  String category;
  double price;
  String imageEmoji;
  String description;
  bool isAvailable;
  int stock;
  int minStock;

  Product({
    required this.id,
    required this.name,
    required this.category,
    required this.price,
    required this.imageEmoji,
    this.description = '',
    this.isAvailable = true,
    this.stock = 50,
    this.minStock = 10,
  });

  Product copyWith({
    String? name,
    String? category,
    double? price,
    String? imageEmoji,
    String? description,
    bool? isAvailable,
    int? stock,
    int? minStock,
  }) {
    return Product(
      id: id,
      name: name ?? this.name,
      category: category ?? this.category,
      price: price ?? this.price,
      imageEmoji: imageEmoji ?? this.imageEmoji,
      description: description ?? this.description,
      isAvailable: isAvailable ?? this.isAvailable,
      stock: stock ?? this.stock,
      minStock: minStock ?? this.minStock,
    );
  }
}

